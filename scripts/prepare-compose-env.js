#!/usr/bin/env node
/**
 * Single source of truth: password + DB name from DATABASE_URL in .env.
 * Writes .env.compose so Docker backend always uses postgres:5432 (not public IP / hairpin).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envFile = process.env.ENV_FILE
  ? path.isAbsolute(process.env.ENV_FILE)
    ? process.env.ENV_FILE
    : path.join(root, process.env.ENV_FILE)
  : path.join(root, '.env');

if (!fs.existsSync(envFile)) {
  console.error(`Missing ${envFile}`);
  process.exit(1);
}

const content = fs.readFileSync(envFile, 'utf8');
const rawLine = content.match(/^DATABASE_URL=(.*)$/m)?.[1]?.trim();
if (!rawLine) {
  console.error('No DATABASE_URL in .env');
  process.exit(1);
}

const line = rawLine.replace(/^["']|["']$/g, '').replace(/\r/g, '');
let parsed;
try {
  parsed = new URL(line.replace(/^postgresql:/i, 'http:'));
} catch {
  console.error('Invalid DATABASE_URL');
  process.exit(1);
}

const user = decodeURIComponent(parsed.username || 'postgres');
const pw = decodeURIComponent(parsed.password || '');
if (!pw) {
  console.error('DATABASE_URL must include a password');
  process.exit(1);
}

const db = (parsed.pathname || '/gizra_db').replace(/^\//, '').split('/')[0] || 'gizra_db';
const params = new URLSearchParams(parsed.search);
if (!params.has('schema')) params.set('schema', 'public');
const query = params.toString();

// Backend uses postgres:5432 + password (same as Raidr-style compose — no pg_hba trust required).
const poolParams = new URLSearchParams(query.replace(/^\?/, ''));
if (!poolParams.has('connection_limit')) poolParams.set('connection_limit', '10');
const internalQuery = poolParams.toString();
const passEnc = encodeURIComponent(pw);
const internal = `postgresql://${encodeURIComponent(user)}:${passEnc}@postgres:5432/${db}?${internalQuery}`;

const composePath = path.join(root, '.env.compose');
const composeBody = `# Generated by scripts/prepare-compose-env.js — do not edit
GIZRA_DATABASE_URL_INTERNAL=${internal}
POSTGRES_PASSWORD=${pw.replace(/\n/g, '')}
`;

fs.writeFileSync(composePath, composeBody, 'utf8');

if (!/^GIZRA_DATABASE_URL_INTERNAL=postgresql:\/\/[^:]+:[^@]+@postgres:5432\//m.test(composeBody)) {
  console.error('Internal URL must include password and host postgres:5432');
  process.exit(1);
}

console.log(`Wrote ${path.basename(composePath)} (backend → postgres:5432 with password; host :5434 uses same password from .env).`);
